function lesson(
  id,
  title,
  category,
  refs,
  prerequisites,
  summary,
  explanation,
  formula,
  pitfall,
  kind,
  focus,
  question,
  options,
  answer,
  why,
  extra = {},
) {
  return {
    id,
    title,
    category,
    level: ['electricity', 'components'].includes(category)
      ? '입문'
      : ['digital', 'interfaces'].includes(category)
        ? '기초'
        : '확장',
    minutes: explanation.length >= 4 ? 8 : 6,
    summary,
    objectives: [summary, `실험의 입력을 바꾸며 ${focus} 관찰하기`],
    explanation,
    formula,
    pitfall,
    experiment: { kind, focus },
    sources: [
      ...refs.map((id) => {
        if (!sourceIndex[id]) throw new Error(`Missing source metadata: ${id}`);
        return sourceIndex[id];
      }),
      ...(primarySources[id] ?? []),
    ],
    prerequisites,
    visual: lessonVisuals[id],
    quiz: { question, options, answer, explanation: why },
    ...extra,
  };
}

